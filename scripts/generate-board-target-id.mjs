import { mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const TARGET_ID_PATTERN = /^[A-Za-z0-9._-]+$/;

/** Generate the only C target-ID definition for a selected board profile. */
export async function generateBoardTargetIdHeader(profile) {
  if (!profile || typeof profile.boardId !== "string" || !TARGET_ID_PATTERN.test(profile.boardId)) {
    throw new Error("board target ID must contain only ASCII letters, digits, '.', '_' or '-'");
  }
  if (typeof profile.targetIdHeaderPath !== "string" || profile.targetIdHeaderPath.length === 0) {
    throw new Error("board profile is missing targetIdHeaderPath");
  }
  const contents = [
    "#pragma once",
    "",
    "/* Generated by scripts/generate-board-target-id.mjs; do not edit. */",
    `#define TSX_BOARD_TARGET_ID ${JSON.stringify(profile.boardId)}`,
    "",
  ].join("\n");
  await mkdir(dirname(profile.targetIdHeaderPath), { recursive: true });
  await writeFile(profile.targetIdHeaderPath, contents, "ascii");
  return profile.targetIdHeaderPath;
}
